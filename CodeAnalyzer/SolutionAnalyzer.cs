using System.Collections.Concurrent;
using System.Xml.Linq;
using Microsoft.Build.Construction;
using Microsoft.Build.Evaluation;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.MSBuild;

namespace CodeAnalyzer;

public sealed class SolutionAnalyzer
{
    public Task<AnalysisSnapshot> AnalyzeAsync(string path, IProgress<string>? progress = null,
        CancellationToken cancellationToken = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(path);
        cancellationToken.ThrowIfCancellationRequested();
        BuildEnvironment.Initialize();
        return AnalyzeCoreAsync(Path.GetFullPath(path), progress, cancellationToken);
    }

    private static async Task<AnalysisSnapshot> AnalyzeCoreAsync(string path, IProgress<string>? progress,
        CancellationToken token)
    {
        var warnings = new ConcurrentQueue<string>();
        var projects = new Dictionary<string, ProjectInfo>(StringComparer.OrdinalIgnoreCase);
        var projectEdges = new HashSet<Dependency>();
        var pending = new Queue<string>(GetProjectPaths(path));
        using(var collection = new ProjectCollection(new Dictionary<string, string> { ["Configuration"] = "Debug" }))
        {
            while(pending.TryDequeue(out var projectPath))
            {
                token.ThrowIfCancellationRequested();
                if(projects.ContainsKey(projectPath)) continue;
                progress?.Report($"Evaluating {Path.GetFileNameWithoutExtension(projectPath)}…");
                var project = collection.LoadProject(projectPath);
                var language = Path.GetExtension(projectPath).Equals(".csproj", StringComparison.OrdinalIgnoreCase) ? "C#" : "F#";
                projects.Add(projectPath, new(projectPath, Path.GetFileNameWithoutExtension(projectPath), language,
                    project.GetPropertyValue("IsTestProject").Equals("true", StringComparison.OrdinalIgnoreCase)));
                foreach(var reference in project.GetItems("ProjectReference"))
                {
                    var target = Path.GetFullPath(reference.EvaluatedInclude, Path.GetDirectoryName(projectPath)!);
                    if(!File.Exists(target))
                    {
                        warnings.Enqueue($"Missing project reference: {projectPath} → {target}");
                        continue;
                    }
                    projectEdges.Add(new(projectPath, target, "references"));
                    pending.Enqueue(target);
                }
                collection.UnloadProject(project);
            }
        }

        using var workspace = MSBuildWorkspace.Create(new Dictionary<string, string> { ["Configuration"] = "Debug" });
        using var failureHandler = workspace.RegisterWorkspaceFailedHandler(e => warnings.Enqueue(e.Diagnostic.Message));
        foreach(var project in projects.Values.Where(p => p.Language == "C#"))
        {
            token.ThrowIfCancellationRequested();
            progress?.Report($"Loading {project.Name}…");
            if(workspace.CurrentSolution.Projects.Any(p => SamePath(p.FilePath, project.Id))) continue;
            await workspace.OpenProjectAsync(project.Id, cancellationToken: token).ConfigureAwait(false);
        }
        if(projects.Values.Any(p => p.Language != "C#"))
            warnings.Enqueue("F# projects are included in the project graph. Type dependencies and complexity cover C# only.");

        var types = new Dictionary<string, TypeInfo>();
        var typeEdges = new HashSet<Dependency>();
        var methods = new List<MethodMetric>();
        foreach(var project in workspace.CurrentSolution.Projects.Where(p => p.Language == LanguageNames.CSharp))
        {
            token.ThrowIfCancellationRequested();
            var info = projects.Values.FirstOrDefault(p => SamePath(project.FilePath, p.Id));
            if(info is null) continue;
            progress?.Report($"Analyzing {info.Name}…");
            var compilation = await project.GetCompilationAsync(token).ConfigureAwait(false);
            if(compilation is null) continue;
            var errors = compilation.GetDiagnostics(token).Where(d => d.Severity == DiagnosticSeverity.Error).ToList();
            if(errors.Count > 0)
                warnings.Enqueue($"{info.Name}: {errors.Count} compilation errors; dependencies may be incomplete. "
                    + string.Join(Environment.NewLine, errors.Take(3)));

            foreach(var document in project.Documents)
            {
                token.ThrowIfCancellationRequested();
                if(IsGenerated(document.FilePath)) continue;
                var root = await document.GetSyntaxRootAsync(token).ConfigureAwait(false);
                if(root is null || root.GetLeadingTrivia().ToFullString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase)) continue;
                var model = compilation.GetSemanticModel(root.SyntaxTree);
                foreach(var declaration in root.DescendantNodes().OfType<BaseTypeDeclarationSyntax>())
                {
                    if(model.GetDeclaredSymbol(declaration, token) is not INamedTypeSymbol symbol) continue;
                    var id = TypeId(symbol);
                    var location = declaration.GetLocation().GetLineSpan();
                    var partSource = $"// {document.FilePath}:{location.StartLinePosition.Line + 1}"
                        + Environment.NewLine + declaration;
                    if(types.TryGetValue(id, out var existing))
                        types[id] = existing with { Source = existing.Source + Environment.NewLine + Environment.NewLine + partSource };
                    else
                        types.Add(id, new(id, symbol.Name, symbol.ToDisplayString(), info.Id,
                            document.FilePath ?? "", location.StartLinePosition.Line + 1, partSource));
                    // Stop at nested types: their dependencies belong to their own nodes.
                    foreach(var node in declaration.DescendantNodes(n => n == declaration || n is not BaseTypeDeclarationSyntax))
                    {
                        token.ThrowIfCancellationRequested();
                        if(node is BaseTypeDeclarationSyntax) continue;
                        var kind = node.AncestorsAndSelf().TakeWhile(n => n != declaration).Any(n => n is BaseListSyntax)
                            ? "inherits / implements" : "uses";
                        var target = model.GetSymbolInfo(node, token).Symbol;
                        var referencedType = target switch
                        {
                            ITypeSymbol t => t,
                            IMethodSymbol m => m.ContainingType,
                            IPropertySymbol p => p.ContainingType,
                            IFieldSymbol f => f.ContainingType,
                            IEventSymbol e => e.ContainingType,
                            _ => null
                        };
                        AddTypeEdges(id, referencedType, kind, typeEdges);
                        if(CyclomaticComplexity.IsFunction(node) && HasBody(node))
                        {
                            var methodSymbol = model.GetDeclaredSymbol(node, token) as IMethodSymbol;
                            var span = node.GetLocation().GetLineSpan();
                            var name = methodSymbol?.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat)
                                ?? $"{symbol.ToDisplayString()}.lambda@{span.StartLinePosition.Line + 1}";
                            methods.Add(new(name, id, info.Id, document.FilePath ?? "", span.StartLinePosition.Line + 1,
                                CyclomaticComplexity.Calculate(node), span.EndLinePosition.Line - span.StartLinePosition.Line + 1,
                                node.ToString()));
                        }
                    }
                }
            }
        }
        return new(projects.Values.OrderBy(p => p.Name).ToArray(), projectEdges.ToArray(),
            types.Values.OrderBy(t => t.FullName).ToArray(),
            typeEdges.Where(e => types.ContainsKey(e.SourceId) && types.ContainsKey(e.TargetId)).ToArray(),
            methods.OrderByDescending(m => m.Complexity).ThenBy(m => m.Name).ToArray(),
            warnings.Distinct().ToArray());
    }

    private static bool HasBody(SyntaxNode node) => node switch
    {
        BaseMethodDeclarationSyntax m => m.Body is not null || m.ExpressionBody is not null,
        AccessorDeclarationSyntax a => a.Body is not null || a.ExpressionBody is not null,
        _ => true
    };

    private static void AddTypeEdges(string source, ITypeSymbol? type, string kind, HashSet<Dependency> edges)
    {
        if(type is IArrayTypeSymbol array) AddTypeEdges(source, array.ElementType, kind, edges);
        if(type is not INamedTypeSymbol named) return;
        var target = TypeId(named);
        if(target != source) edges.Add(new(source, target, kind));
        foreach(var argument in named.TypeArguments)
            AddTypeEdges(source, argument, kind, edges);
    }

    private static string TypeId(INamedTypeSymbol symbol) =>
        $"{symbol.ContainingAssembly.Identity.Name}:{symbol.OriginalDefinition.GetDocumentationCommentId()}";

    private static bool SamePath(string? left, string right) =>
        left is not null && Path.GetFullPath(left).Equals(right, StringComparison.OrdinalIgnoreCase);

    private static bool IsGenerated(string? path) => path is null
        || path.Split(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar).Any(p => p is "obj" or "bin")
        || path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
        || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase);

    private static IEnumerable<string> GetProjectPaths(string path)
    {
        if(!File.Exists(path)) throw new FileNotFoundException("The selected solution or project does not exist.", path);
        var directory = Path.GetDirectoryName(path)!;
        return Path.GetExtension(path).ToLowerInvariant() switch
        {
            ".slnx" => XDocument.Load(path).Descendants("Project")
                .Select(p => p.Attribute("Path")?.Value).OfType<string>()
                .Select(p => Path.GetFullPath(p, directory)).ToArray(),
            ".sln" => SolutionFile.Parse(path).ProjectsInOrder
                .Where(p => p.ProjectType == SolutionProjectType.KnownToBeMSBuildFormat)
                .Select(p => p.AbsolutePath).ToArray(),
            ".csproj" or ".fsproj" => [path],
            _ => throw new ArgumentException("Choose a .slnx, .sln, .csproj, or .fsproj file.", nameof(path))
        };
    }
}
